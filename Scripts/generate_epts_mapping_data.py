#!/usr/bin/env python3
"""Generate the app's pinned Swift mapping data from the reviewed JSON catalog."""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any

from epts_mapping_tools import load_catalog


def table_identifier(table: dict[str, Any]) -> str:
    return f'reference{table["referenceYear"]}'


def render_table(table: dict[str, Any]) -> str:
    values = []
    bounds = table["upperBounds"]
    for start in range(0, len(bounds), 6):
        chunk = ", ".join(f"{value:.14f}" for value in bounds[start:start + 6])
        values.append(f"            {chunk},")

    return "\n".join((
        f"    private static let {table_identifier(table)} = EPTSMappingTable(",
        f'        referenceYear: {table["referenceYear"]},',
        f'        publicationYear: {table["publicationYear"]},',
        f'        databaseAsOf: "{table["databaseAsOf"]}",',
        f'        sourceURL: "{table["sourceURL"]}",',
        "        upperBounds: [",
        *values,
        "        ]",
        "    )",
    ))


def render_swift(catalog_path: Path) -> str:
    catalog = load_catalog(catalog_path)
    tables = [render_table(table) for table in catalog["tables"]]
    identifiers = [table_identifier(table) for table in catalog["tables"]]
    current_identifier = identifiers[-1]

    return "\n".join((
        "// Generated by Scripts/generate_epts_mapping_data.py from Research/epts_mapping_tables.json.",
        "// Reference year is the December 31 waitlist snapshot; publication is the following spring.",
        "// Do not hand-edit threshold values.",
        "",
        "import Foundation",
        "",
        "struct EPTSMappingTable: Identifiable, Equatable, Sendable {",
        "    let referenceYear: Int",
        "    let publicationYear: Int",
        "    let databaseAsOf: String",
        "    let sourceURL: String",
        "    let upperBounds: [Double]",
        "",
        "    var id: Int { referenceYear }",
        "",
        "    /// Implements the OPTN intervals: raw EPTS > lower and <= upper.",
        "    func percentile(for rawScore: Double) -> Int {",
        "        // Invalid values must never be interpreted as top-priority EPTS 0%.",
        "        guard rawScore.isFinite else { return 100 }",
        "",
        "        var lowerIndex = 0",
        "        var upperIndex = upperBounds.count",
        "        while lowerIndex < upperIndex {",
        "            let middleIndex = lowerIndex + (upperIndex - lowerIndex) / 2",
        "            if rawScore <= upperBounds[middleIndex] {",
        "                upperIndex = middleIndex",
        "            } else {",
        "                lowerIndex = middleIndex + 1",
        "            }",
        "        }",
        "        return lowerIndex < upperBounds.count ? lowerIndex : 100",
        "    }",
        "}",
        "",
        "enum EPTSMappingTables {",
        *tables,
        "",
        "    // Keep launch light: requesting the current table initializes only its data.",
        f"    static let current = {current_identifier}",
        "",
        "    /// Annual reference populations, initialized only when historical data is requested.",
        "    static let all: [EPTSMappingTable] = [",
        *(f"        {identifier}," for identifier in identifiers),
        "    ]",
        "}",
        "",
    ))


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--catalog", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Fail if the generated output differs; do not write",
    )
    args = parser.parse_args()

    output = render_swift(args.catalog)
    if args.check:
        existing = args.output.read_text(encoding="utf-8") if args.output.exists() else ""
        if existing != output:
            raise SystemExit(f"{args.output} is stale; regenerate it")
        print(f"{args.output} is current")
        return

    args.output.write_text(output, encoding="utf-8")
    print(f"Generated {args.output}")


if __name__ == "__main__":
    main()
